"""Reproduce terrain error against the analytic synthetic surface; no sensor data."""
import json,math,statistics
from pathlib import Path
from narwhal_topo.demo import survey,terrain
from narwhal_topo.mapping import build
from narwhal_topo.model import Settings
from narwhal_topo.export import bundle,point_csv

out=Path('runs/reference');out.mkdir(parents=True,exist_ok=True)
rows=[]
for cell in (.25,.5,1.0):
    s=Settings(cell_size=cell,min_points=1 if cell==.25 else 2,contour_interval=.5)
    result,pts=build(survey(),s,{'kind':'synthetic','seed':532})
    g=result['grid'];errors=[]
    for n,z in enumerate(g['z']):
        if z is not None:errors.append(z-terrain(g['x0']+(n%g['cols']+.5)*cell,g['y0']+(n//g['cols']+.5)*cell))
    stats={k:v for k,v in result['stats'].items() if k!='build_ms'}
    stats.update(bias_vs_cell_center_m=statistics.mean(errors),rmse_vs_cell_center_m=math.sqrt(statistics.mean(e*e for e in errors)))
    rows.append(stats)
    if cell==.5:(out/'survey.zip').write_bytes(bundle(result,pts))
(out/'results.json').write_text(json.dumps({'evidence':'synthetic only; analytic surface is known to the generator','seed':532,'results':rows},indent=2)+'\n')
text='# Reproducible synthetic results\n\nGenerated by `PYTHONPATH=src python examples/reproduce.py`. Same seeded 60 x 40 m scene, 0.025 m Gaussian elevation noise and occasional synthetic spikes. No physical sensor, pose error or water model participates.\n\n| Cell (m) | Minimum count | Valid cells | Coverage | Robust rejections | Cell-center RMSE (m) | Bias (m) |\n|---|---|---|---|---|---|---|\n'
for r in rows:text+=f"| {r['cell_size_m']} | {1 if r['cell_size_m']==.25 else 2} | {r['valid_cells']} | {r['coverage']:.5f} | {r['robust_outliers']} | {r['rmse_vs_cell_center_m']:.6f} | {r['bias_vs_cell_center_m']:.6f} |\n"
text+='\nThe 0.25 m case has one point per cell, so the cell-wise spike filter cannot identify isolated spikes. Coarser cells have more support but smooth detail and compare a median of spatially distributed samples with center truth. This is a sensitivity demonstration, not evidence of achieved map accuracy.\n'
(out/'results.md').write_text(text)
# Compact fixture covering several populated cells for import checks.
(out/'sample.csv').write_text(point_csv(survey()[:2400]))
print(text)
